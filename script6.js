        let selectedItems = [];

        function updateTotal() {
            selectedItems = [];
            let total = 0;
            const nights = parseInt(document.getElementById('nights-count').innerText) || 1;
            
            const inputs = document.querySelectorAll('.rate-qty');
            inputs.forEach(input => {
                const qty = parseInt(input.value) || 0;
                if(qty > 0) {
                    const price = parseFloat(input.dataset.price);
                    const name = input.dataset.name;
                    const isAccomm = input.dataset.isAccomm === 'true';
                    
                    const multiplier = isAccomm ? nights : 1;
                    const itemTotal = qty * price * multiplier;
                    
                    total += itemTotal;
                    
                    const desc = isAccomm 
                        ? `${name} (${nights} night${nights > 1 ? 's' : ''})` 
                        : `${name}`;
                        
                    selectedItems.push({ name: desc, qty, price, total: itemTotal });
                }
            });
            
            const bb = document.getElementById('booking-bar');
            if(total > 0) {
                bb.style.display = 'flex';
                bb.style.justifyContent = 'center';
                bb.style.alignItems = 'center';
                document.getElementById('booking-total').innerText = 'Total: N$ ' + total.toLocaleString('en-US', {minimumFractionDigits: 2, maximumFractionDigits: 2});
            } else {
                bb.style.display = 'none';
            }

            // Flash the Finalise Booking tab if ready
            const tabBtn5 = document.getElementById('tab-btn-5');
            const din = document.getElementById('b-date-in').value;
            const dout = document.getElementById('b-date-out').value;
            if(tabBtn5) {
                if(total > 0 && din && dout && !tabBtn5.classList.contains('active')) {
                    tabBtn5.classList.add('flash-tab');
                } else {
                    tabBtn5.classList.remove('flash-tab');
                }
            }

            if(document.getElementById('tab-5').classList.contains('active')) {
                renderBookingSummary();
            }
        }

        function renderBookingSummary() {
            const summary = document.getElementById('booking-summary');
            if (selectedItems.length === 0) {
                summary.innerHTML = '<p style="color: var(--text-muted); margin: 0;">Please select rates or activities from the tabs above to build your booking.</p>';
                return;
            }

            let html = '<ul style="list-style:none; padding:0; margin:0;">';
            selectedItems.forEach(item => {
                html += '<li style="margin-bottom: 10px; border-bottom: 1px solid rgba(0,0,0,0.05); padding-bottom: 10px; display: flex; justify-content: space-between;">';
                html += '<span><strong>' + item.qty + ' pax</strong> ' + item.name + '</span>';
                html += '<span style="color: var(--brand-accent); font-weight: 600;">N$ ' + item.total.toLocaleString('en-US', {minimumFractionDigits: 2}) + '</span>';
                html += '</li>';
            });
            
            const total = selectedItems.reduce((acc, item) => acc + item.total, 0);
            html += '<li style="margin-top: 15px; display: flex; flex-direction: column; gap: 8px;">';
            html += '<div style="display: flex; justify-content: space-between; font-size: 1.2rem; font-family: var(--font-head); font-weight: 600;">';
            html += '<span>Grand Total</span>';
            html += '<span style="color: var(--text-main);">N$ ' + total.toLocaleString('en-US', {minimumFractionDigits: 2}) + '</span>';
            html += '</div>';
            
            const lodgeName = document.getElementById('d-title') ? document.getElementById('d-title').innerText : '';
            const dateIn = document.getElementById('b-date-in') ? document.getElementById('b-date-in').value : '';
            const dateOut = document.getElementById('b-date-out') ? document.getElementById('b-date-out').value : '';
            if (lodgeName || (dateIn && dateOut)) {
                html += '<div style="font-size: 0.85rem; color: var(--text-muted); padding-top: 8px; border-top: 1px solid rgba(0,0,0,0.05);">';
                if (lodgeName) {
                    html += '<div style="margin-bottom: 3px;"><strong>Property:</strong> ' + lodgeName + '</div>';
                }
                if (dateIn && dateOut) {
                    let dateStr = dateIn + ' to ' + dateOut;
                    try {
                        const [y1, m1, d1] = dateIn.split('-');
                        const [y2, m2, d2] = dateOut.split('-');
                        const dt1 = new Date(y1, parseInt(m1)-1, d1);
                        const dt2 = new Date(y2, parseInt(m2)-1, d2);
                        const nights = Math.round((dt2 - dt1) / (1000 * 60 * 60 * 24));
                        dateStr = `${d1}-${m1}-${y1.slice(2)} to ${d2}-${m2}-${y2.slice(2)} (${nights} Night${nights !== 1 ? 's' : ''})`;
                    } catch(e) {}
                    html += '<div><strong>Dates:</strong> ' + dateStr + '</div>';
                }
                html += '</div>';
            }
            
            html += '</li></ul>';
            
            summary.innerHTML = html;
        }

